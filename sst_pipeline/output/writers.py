"""
writers.py
----------
Observation exchange formats.

* CCSDS TDM (Tracking Data Message, CCSDS 503.0-B-2), KVN encoding, ANGLE_TYPE
  = RADEC: the standard format for optical angles-only SST data exchanged
  with SST networks and satellite operators.
* ADES PSV (IAU Astrometric Data Exchange Standard): written with a valid
  ADES header and field set for archiving and tools that read ADES. Note:
  the MPC does not accept observations of artificial satellites.

Only observations from catalogue-verified plates are written unless
output.report_unverified_astrometry is true.

RA/Dec convention (both formats): topocentric, star-referenced
(astrometric) ICRF positions — the plate solution removes annual
aberration; no aberration or light-time correction has been applied to the
object itself.
"""

from __future__ import annotations

from datetime import datetime, timezone

import pandas as pd

from sst_pipeline import __version__
from sst_pipeline.astrometry.position_extractor import Detection
from sst_pipeline.tracking.linker import Tracklet


def _reportable(trs: list[Tracklet], allow_unverified: bool):
    for tr in trs:
        obs = [d for d in tr.members if d.astrometry_verified or allow_unverified]
        if obs:
            yield tr, obs


def write_detections_csv(dets: list[Detection], path: str) -> str:
    cols = list(Detection.__dataclass_fields__)
    pd.DataFrame([d.to_dict() for d in dets], columns=cols).to_csv(path, index=False)
    return path


def write_tracklets_csv(trs: list[Tracklet], path: str, uct_only: bool = False) -> str:
    rows = [t.to_dict() for t in trs if not (uct_only and t.identified)]
    pd.DataFrame(rows).to_csv(path, index=False)
    return path


def write_tdm(trs: list[Tracklet], path: str, site: dict, allow_unverified: bool) -> int:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")
    stn = site.get("iau_obs_code") or site.get("name", "SSAH")
    lines = ["CCSDS_TDM_VERS = 2.0",
             f"COMMENT Generated by SSAH SST optical pipeline v{__version__}",
             f"COMMENT Site lat={site['latitude_deg']} lon={site['longitude_deg']} h={site['height_m']} m",
             f"CREATION_DATE = {now}", "ORIGINATOR = SSAH", ""]
    n = 0
    for tr, obs in _reportable(trs, allow_unverified):
        obj = f"NORAD-{tr.norad_id}" if tr.identified else f"UCT-{tr.tracklet_id}"
        lines += ["META_START",
                  f"COMMENT tracklet {tr.tracklet_id} kind={tr.kind} quality={tr.quality}",
                  "COMMENT RA/DEC topocentric, star-referenced (astrometric) ICRF; "
                  "epochs = mid-exposure UTC",
                  "TIME_SYSTEM = UTC", f"PARTICIPANT_1 = {stn}", f"PARTICIPANT_2 = {obj}",
                  "MODE = SEQUENTIAL", "PATH = 2,1", "ANGLE_TYPE = RADEC",
                  "REFERENCE_FRAME = ICRF",
                  f"START_TIME = {obs[0].epoch_utc}", f"STOP_TIME = {obs[-1].epoch_utc}",
                  "META_STOP", "DATA_START"]
        for d in obs:
            lines.append(f"ANGLE_1 = {d.epoch_utc} {d.ra_deg:.7f}")
            lines.append(f"ANGLE_2 = {d.epoch_utc} {d.dec_deg:+.7f}")
            n += 1
        lines += ["DATA_STOP", ""]
    with open(path, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    return n


ADES_FIELDS = ["permID", "provID", "trkSub", "mode", "stn", "obsTime", "ra", "dec",
               "rmsRA", "rmsDec", "astCat", "mag", "rmsMag", "band", "remarks"]


def write_ades_psv(trs: list[Tracklet], path: str, site: dict, out_cfg: dict,
                   instrument: dict, ast_cat: str, allow_unverified: bool) -> int:
    hdr = ["# version=2022", "# observatory", f"! mpcCode {site.get('iau_obs_code', 'XXX')}",
           "# submitter", f"! name {out_cfg.get('ades_contact_name', '[PLACEHOLDER]')}",
           "# telescope", f"! aperture {float(instrument.get('aperture_mm', 0)) / 1000:.3f}",
           "! design reflector", "! detector CCD",
           "# comment", "! line Artificial-satellite observations; not for MPC submission",
           "! line Positions: topocentric star-referenced ICRF, mid-exposure UTC"]
    rows = []
    for tr, obs in _reportable(trs, allow_unverified):
        for d in obs:
            show_mag = d.mag is not None and d.photometry_ok and d.mag_band
            rows.append({
                "permID": "", "provID": "", "trkSub": tr.tracklet_id[:8], "mode": "CCD",
                "stn": site.get("iau_obs_code", "XXX"),
                "obsTime": d.epoch_utc + "Z", "ra": f"{d.ra_deg:.7f}", "dec": f"{d.dec_deg:+.7f}",
                "rmsRA": f"{d.ra_err_arcsec:.3f}", "rmsDec": f"{d.dec_err_arcsec:.3f}",
                "astCat": ast_cat,
                "mag": f"{d.mag:.2f}" if show_mag else "",
                "rmsMag": f"{d.mag_err:.2f}" if show_mag else "",
                "band": d.mag_band if show_mag else "",
                "remarks": (f"NORAD {tr.norad_id}" if tr.identified else "UCT") + f" {tr.kind}",
            })
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(hdr) + "\n")
        f.write("|".join(ADES_FIELDS) + "\n")
        for r in rows:
            f.write("|".join(r[k] for k in ADES_FIELDS) + "\n")
    return len(rows)
